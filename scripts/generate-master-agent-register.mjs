/** @type {Record<string, string>} */
const DEFAULT_STATUS = {
  AURA: 'Partial',
  EXEC: 'Partial',
  FIN: 'Partial',
  default: 'Missing',
};

function defaultStatusFor(dept, name, id) {
  if (REGISTRY_MAP[id]) return 'Partial';
  if (dept === 'AURA') return 'Partial';
  if (dept === 'EXEC' && name === 'Executive Command Agent') return 'Partial';
  if (dept === 'COM' && name === 'Facebook Messenger Agent') return 'Provider-blocked';
  if (dept === 'MKT' && name === 'Social Media Agent') return 'Provider-blocked';
  if (dept === 'MKT' && name === 'Publishing and Scheduling Agent') return 'Provider-blocked';
  if (dept === 'AUD') return 'Missing';
  return 'Missing';
}

const agents = [];
for (const [dept, names] of Object.entries(DEPARTMENTS)) {
  names.forEach((name, index) => {
    const id = `${dept}-${String(index + 1).padStart(3, '0')}`;
    agents.push({
      id,
      dept,
      name,
      registryKey: REGISTRY_MAP[id] ?? null,
      status: defaultStatusFor(dept, name, id),
    });
  });
}

const deptTotals = {};
for (const a of agents) {
  deptTotals[a.dept] = (deptTotals[a.dept] ?? 0) + 1;
}

const statusTotals = {};
for (const a of agents) {
  statusTotals[a.status] = (statusTotals[a.status] ?? 0) + 1;
}

const summary = {
  totalUniqueAgents: agents.length,
  departmentTotals: deptTotals,
  statusTotals,
  agents,
};

writeFileSync(join(ROOT, 'docs/.agent-register-data.json'), JSON.stringify(summary, null, 2));
console.log(JSON.stringify({ total: agents.length, deptTotals, statusTotals }, null, 2));
